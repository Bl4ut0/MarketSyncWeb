import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const output = process.argv[2];
if (!output) throw new Error('Pass the output path for the MarketSyncData analytics engine.');
const root = fileURLToPath(new URL('../', import.meta.url));

await build({
  absWorkingDir: root,
  stdin: {
    resolveDir: root,
    loader: 'ts',
    contents: `
export { normalizeSnapshot, parseDatasetIndex } from '@marketsync/shared';
export { enrichEntry, groupAuctionVariants } from './client/src/lib/auctionRows.ts';
export { indexMarketObservations, analyzeMarket, MAX_ANALYTICS_CAPTURES } from './client/src/lib/marketAnalytics.ts';
export { HISTORY_RANGES, selectHistoryBlocks } from './client/src/lib/priceHistory.ts';
export { packAnalyticsReport } from './client/src/lib/preparedAnalytics.ts';
`,
  },
  alias: { '@marketsync/shared': resolve(root, 'shared/src/index.ts') },
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'cjs',
  banner: { js: '// Generated by MarketSyncWeb/scripts/build-analytics-engine.mjs from the shared browser calculator.' },
  outfile: resolve(output),
});
